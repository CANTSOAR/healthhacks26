"""Layout handling: turns a contracts/layout.schema.json file into the counts, bay table and
walking distances the simulator needs, and renders the per-hospital layout back out.

Pure python, used at scenario load and in the snapshot path, never in the tick path.
"""
from __future__ import annotations

import copy
import math

BAY_CLASSES = ["resus", "main", "fast", "peds", "hall"]
C_RESUS, C_MAIN, C_FAST, C_PEDS, C_HALL = range(5)
RELOCATE_VARIANTS = ["none", "triage_next_to_imaging", "fast_track_by_entrance"]


def slot_xy(room: dict, k: int, n: int | None = None):
    """Position of the k-th patient slot inside a room rectangle (explicit slots, else a grid)."""
    slots = room.get("slots")
    if slots:
        s = slots[k % len(slots)]
        return float(s[0]), float(s[1])
    cap = max(1, int(n if n is not None else room.get("capacity") or 1))
    if cap == 1:
        return float(room["x"]), float(room["z"])
    w, d = float(room["w"]), float(room["d"])
    cols = max(1, int(math.ceil(math.sqrt(cap * max(w, 0.1) / max(d, 0.1)))))
    rows = int(math.ceil(cap / cols))
    k = k % (cols * rows)
    cx, cz = k % cols, k // cols
    return (room["x"] - w / 2 + (cx + 0.5) * w / cols, room["z"] - d / 2 + (cz + 0.5) * d / rows)


def _centroid(rooms, idxs):
    if not idxs:
        return None
    return (sum(rooms[i]["x"] for i in idxs) / len(idxs), sum(rooms[i]["z"] for i in idxs) / len(idxs))


def _dist(a, b, factor):
    if a is None or b is None:
        return 0.0
    return factor * (abs(a[0] - b[0]) + abs(a[1] - b[1]))


class LayoutModel:
    def __init__(self, layout: dict, bay_types: dict, ward_types: list, hall_max: int, future_main: int,
                 path_factor: float = 1.0):
        self.base = copy.deepcopy(layout)
        self.path_factor = path_factor
        rooms = self.base["rooms"]
        self.n_file_rooms = len(rooms)
        by_type: dict[str, list[int]] = {}
        for i, r in enumerate(rooms):
            if r.get("physical", True) is False and r["type"] not in bay_types:
                continue
            by_type.setdefault(r["type"], []).append(i)
        self.by_type = by_type
        cls_of = {k: BAY_CLASSES.index(v) for k, v in bay_types.items()}

        # ---- bays: one entry per patient space
        self.bays: list[dict] = []           # {cls, room, slot, exists0}
        planned = []
        for i, r in enumerate(rooms):
            if r["type"] in cls_of:
                c = cls_of[r["type"]]
                if "hallway" in (r.get("catalog_ref") or ""):
                    c = C_HALL
                for s in range(max(1, int(r["capacity"])) if r["capacity"] else 0):
                    e = dict(cls=c, room=i, slot=s, exists0=r.get("physical", True) is not False)
                    (self.bays if e["exists0"] or c != C_MAIN else planned).append(e)
        main = [b for b in self.bays if b["cls"] == C_MAIN]
        ref = rooms[main[-1]["room"]] if main else (rooms[self.bays[-1]["room"]] if self.bays else
                                                  dict(x=10.0, z=10.0, w=3.0, d=4.0, zone="ED main"))
        # hallway overflow spaces (appended rooms unless the file already has them)
        n_hall = sum(1 for b in self.bays if b["cls"] == C_HALL)
        corr = [rooms[i] for i in by_type.get("corridor", [])]
        host = max(corr, key=lambda r: r["w"] * r["d"]) if corr else None
        for k in range(n_hall, hall_max):
            if host is not None:
                horiz = host["w"] >= host["d"]
                L = host["w"] if horiz else host["d"]
                step = L / max(1, hall_max)
                off = -L / 2 + (k + 0.5) * step
                x = host["x"] + (off if horiz else 0.0)
                z = host["z"] + (0.0 if horiz else off)
                w, d = (min(2.2, step * 0.9), min(1.0, host["d"])) if horiz else (min(1.0, host["w"]), min(2.2, step * 0.9))
            else:
                x, z, w, d = ref["x"] + (k % 8) * 2.4, ref["z"] + ref["d"] + 1.5 + (k // 8) * 1.4, 2.2, 1.0
            rooms.append(dict(id=f"hall-{k + 1:02d}", type="treatment_bay", label=f"Hallway space {k + 1}",
                              zone="Hallway overflow", x=round(x, 2), z=round(z, 2), w=round(w, 2), d=round(d, 2),
                              floor=0, capacity=1, physical=True, catalog_ref="space/hallway_overflow",
                              provenance="inferred",
                              source="Generated by the simulator: stretcher spaces along the corridor, opened by the overflow_bays action",
                              note="Closed unless the manager opens overflow"))
            self.bays.append(dict(cls=C_HALL, room=len(rooms) - 1, slot=0, exists0=True))
        # future main bays (planned rooms from the file first, then generated)
        fut = planned[:future_main]
        if len(fut) < future_main:
            bx = [rooms[b["room"]] for b in self.bays if b["cls"] in (C_MAIN, C_RESUS, C_FAST, C_PEDS)]
            zmax = max((r["z"] + r["d"] / 2 for r in bx), default=20.0)
            xmin = min((r["x"] - r["w"] / 2 for r in bx), default=5.0)
            w, d = ref["w"], ref["d"]
            for k in range(future_main - len(fut)):
                x = xmin + w / 2 + (k % 12) * (w + 0.3)
                z = zmax + 1.0 + d / 2 + (k // 12) * (d + 0.3)
                rooms.append(dict(id=f"bay-new-{k + 1:02d}", type="treatment_bay", label=f"New bay {k + 1}",
                                  zone="ED expansion", x=round(x, 2), z=round(z, 2), w=w, d=d, floor=0, capacity=1,
                                  physical=False, catalog_ref="space/treatment_bay", provenance="inferred",
                                  source="Generated by the simulator: position reserved for bays built by the bays_delta action",
                                  note="Not built unless the manager adds bays"))
                fut.append(dict(cls=C_MAIN, room=len(rooms) - 1, slot=0, exists0=False))
        self.bays.extend(fut)
        self.rooms = rooms
        self.n_rooms = len(rooms)
        self.n_bays = len(self.bays)
        self.bay_cls = [b["cls"] for b in self.bays]
        self.bay_room = [b["room"] for b in self.bays]

        def first(t):
            return by_type.get(t, [None])[0]

        self.waiting = first("waiting_room")
        self.entrance = first("entrance")
        self.amb = first("ambulance_bay")
        if self.amb is None:
            self.amb = self.waiting if self.waiting is not None else 0
        if self.waiting is None:
            self.waiting = self.entrance if self.entrance is not None else 0
        self.triage_rooms = by_type.get("triage", [])
        self.n_triage_rooms = sum(max(1, rooms[i]["capacity"]) for i in self.triage_rooms)
        self.results_rooms = by_type.get("results_waiting", [])
        # ---- scanners
        self.scan_rooms = {t: list(by_type.get(t, [])) for t in ("xray", "ct")}
        self.equipment = list(self.base.get("equipment", []))
        self.scan_units = {}
        for t in ("xray", "ct"):
            n = sum(1 for e in self.equipment if e["type"] == t)
            if n == 0:
                n = sum(max(1, rooms[i]["capacity"]) for i in self.scan_rooms[t])
            self.scan_units[t] = n
        # ---- ward pool
        self.ward_rooms = [i for i, r in enumerate(rooms) if r["type"] in ward_types and r.get("physical", True) is not False]
        self.ward_cap = sum(int(rooms[i]["capacity"]) for i in self.ward_rooms)
        ward_units = [i for i in self.ward_rooms if rooms[i]["type"] == "ward_unit"]
        self.ward_flex_room = (ward_units or self.ward_rooms or [None])[-1]
        self.n_ed_bays0 = sum(1 for b in self.bays if b["exists0"] and b["cls"] != C_HALL)
        self.variant_rooms = [self._variant_rooms(v) for v in range(len(RELOCATE_VARIANTS))]
        self.legs = [self._legs(v) for v in range(len(RELOCATE_VARIANTS))]

    # ---- relocation variants -------------------------------------------------------------
    def _variant_rooms(self, v: int):
        rooms = self.rooms
        if v == 0:
            return rooms
        rooms = copy.deepcopy(rooms)
        if v == 1:      # triage rooms moved beside imaging
            img = self.scan_rooms["xray"] + self.scan_rooms["ct"]
            c = _centroid(rooms, img)
            if c is not None and self.triage_rooms:
                left = min(rooms[i]["x"] - rooms[i]["w"] / 2 for i in img)
                for k, i in enumerate(self.triage_rooms):
                    r = rooms[i]
                    r["x"] = round(left - 0.5 - r["w"] / 2 - (k // 2) * (r["w"] + 0.3), 2)
                    r["z"] = round(c[1] + (k % 2 - 0.5) * (r["d"] + 0.3), 2)
                    r["provenance"] = "inferred"
                    r["note"] = "Relocated next to imaging by the manager (relocate action)"
        elif v == 2:    # fast track moved beside the waiting room / entrance
            ft = [b["room"] for b in self.bays if b["cls"] == C_FAST]
            c = _centroid(rooms, ft)
            if c is not None and self.waiting is not None:
                wr = rooms[self.waiting]
                tx = wr["x"] + wr["w"] / 2 + 1.0
                minx = min(rooms[i]["x"] - rooms[i]["w"] / 2 for i in ft)
                dx, dz = tx - minx, wr["z"] - c[1]
                for i in set(ft):
                    r = rooms[i]
                    r["x"] = round(r["x"] + dx, 2)
                    r["z"] = round(r["z"] + dz, 2)
                    r["provenance"] = "inferred"
                    r["note"] = "Relocated beside the waiting room by the manager (relocate action)"
        return rooms

    def _legs(self, v: int):
        """Walking distances in metres between zone centroids for relocation variant v.
        Order: [wait->triage] + [wait->bay class c]*5 + [amb->bay class c]*5 + [bay c->xray, bay c->ct]*5
               + [bay c->ward]*5  (21 values + 5)."""
        rooms = self.variant_rooms[v]
        f = self.path_factor
        wait = _centroid(rooms, [self.waiting])
        amb = _centroid(rooms, [self.amb])
        tri = _centroid(rooms, self.triage_rooms)
        cc = []
        for c in range(len(BAY_CLASSES)):
            idx = [b["room"] for b in self.bays if b["cls"] == c and (b["exists0"] or c != C_MAIN)]
            cc.append(_centroid(rooms, idx))
        if cc[C_HALL] is None:
            cc[C_HALL] = cc[C_MAIN]
        sx = _centroid(rooms, self.scan_rooms["xray"]) or _centroid(rooms, self.scan_rooms["ct"])
        sc = _centroid(rooms, self.scan_rooms["ct"]) or sx
        ward = _centroid(rooms, self.ward_rooms)
        legs = [_dist(wait, tri, f)]
        legs += [_dist(wait, c, f) for c in cc]
        legs += [_dist(amb, c, f) for c in cc]
        for c in cc:
            legs += [_dist(c, sx, f), _dist(c, sc, f)]
        legs += [_dist(c, ward, f) for c in cc]
        return legs

    # ---- output --------------------------------------------------------------------------
    def render(self, version: int, variant: int, bay_exists: list, ward_cap: int, extra_equipment: list) -> dict:
        """Layout dict for one hospital given its structural state."""
        out = {k: v for k, v in self.base.items() if k not in ("rooms", "equipment")}
        rooms = copy.deepcopy(self.variant_rooms[variant])
        for j, b in enumerate(self.bays):
            if b["cls"] == C_HALL:
                continue
            r = rooms[b["room"]]
            if r["capacity"] <= 1:
                was = r.get("physical", True) is not False
                r["physical"] = bool(bay_exists[j])
                if was and not bay_exists[j]:
                    r["note"] = "Closed by the manager (bays_delta)"
                elif not was and bay_exists[j]:
                    r["note"] = "Built by the manager (bays_delta)"
        if self.ward_flex_room is not None:
            r = rooms[self.ward_flex_room]
            r["capacity"] = max(0, int(r["capacity"]) + int(ward_cap) - self.ward_cap)
        out["rooms"] = rooms
        out["equipment"] = copy.deepcopy(self.equipment) + list(extra_equipment)
        out["version"] = int(version)
        return out
