"""Build the digital-twin inputs of one hospital from public data.

    .venv/bin/python -m twin.build --ccn 330024 --id mount_sinai --expect "mount sinai" "new york"

Reads the tracked extracts in data/processed/hospitals/<ccn>/ (fetching any that are missing; `--fetch` re-fetches all,
see twin/fetch.py) and writes
    catalog/hospitals/<id>.yaml           hospital attributes + `catalog_overrides` for hospital-specific values of the shared catalog
    catalog/hospitals/<id>.layout.json    schema-valid layout from the counts; every room position is `inferred`
    twin/reports/<id>/DATA.md             every attribute with value, unit, source tag and citation; coverage; roster; what is not public

A hospital file that was not generated here (rwjuh_nb.yaml, hand-built) is only ADDED to: new attributes and a
`catalog_overrides` block holding verbatim copies of the shared-catalog nodes, so its behaviour cannot change; its layout
is left alone. Never writes catalog/hospitals/<id>.calibration.yaml (owned by twin/calibrate.py).
"""
from __future__ import annotations

import argparse
import datetime as dt
import json

import yaml

from . import layout as layout_mod
from . import report
from .derive import SOURCES, Twin, shared_node
from .sources._common import REPO, atomic_write_text, norm_ccn, read_extract

HOSP = REPO / "catalog" / "hospitals"
BEGIN = "      # ---- BEGIN twin.build additions (generated by `python -m twin.build`; do not edit by hand) ----"
END = "# ---- END twin.build additions ----"


def _dump(obj, indent=0) -> str:
    txt = yaml.safe_dump(obj, sort_keys=False, default_flow_style=False, width=150, allow_unicode=True)
    return "".join((" " * indent + ln if ln.strip() else ln) for ln in txt.splitlines(True))


def _same(a, b) -> bool:
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(a - b) <= 1e-9 + 0.0051 * max(abs(a), abs(b))
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(_same(x, y) for x, y in zip(a, b))
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(_same(a[k], b[k]) for k in a)
    return a == b


def write_generated(t: Twin) -> dict:
    """New hospital: the whole file is generated."""
    f = t.fac
    doc = {
        "schema_version": 1, "entity_type": "hospital",
        "description": (f"{t.name}, {f.get('City/Town', '').title()} {f.get('State')} (CMS certification number {t.ccn}) - a MODEL built from public data alone by twin/build.py. "
                        "Not affiliated with or endorsed by the hospital. Patient flows, staffing and outcomes are simulated, not the hospital's operational data. Staff are fictional. "
                        f"Every attribute is tagged measured / literature / assumed with its citation; the readable version is twin/reports/{t.id}/DATA.md."),
        "generated_by": "twin.build", "generated_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"), "cms_certification_number": t.ccn,
        "layout_file": f"catalog/hospitals/{t.id}.layout.json",
        "variants": {t.id: {"label": t.label, "attributes": t.attrs}},
        "catalog_overrides": t.overrides,
    }
    head = (f"# GENERATED by `python -m twin.build --ccn {t.ccn} --id {t.id}` from data/processed/hospitals/{t.ccn}/ - edit twin/derive.py, not this file.\n"
            "# Shape: contracts/catalog.schema.json plus `catalog_overrides` (sim/config.py load_scenario). Fitted values belong in\n"
            f"# catalog/hospitals/{t.id}.calibration.yaml (twin/calibrate.py), which is applied on top of this file.\n")
    atomic_write_text(HOSP / f"{t.id}.yaml", head + _dump(doc))
    return dict(mode="generated", attrs=t.attrs, overrides=t.overrides, check=[])


def write_augmented(t: Twin, path) -> dict:
    """Hand-built hospital file: append new attributes and a catalog_overrides block as text; nothing existing is touched."""
    text = path.read_text()
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip("\n") + "\n"
    existing = yaml.safe_load(text)
    if existing.get("catalog_overrides"):
        raise SystemExit(f"{path} already has a hand-written catalog_overrides block; refusing to add a second one")
    have = existing["variants"][t.id]["attributes"]
    new = {k: v for k, v in t.attrs.items() if k not in have}
    # verbatim copies of the shared nodes: the hand-built hospital IS the hospital the shared catalog was written for
    overrides, check = {}, []
    for pth, node in t.overrides.items():
        sh = shared_node(t.shared, pth)
        if sh is None:
            continue
        overrides[pth] = sh
        check.append({"path": pth, "catalog": sh.get("value"), "catalog_source": sh.get("source"), "pipeline": node.get("value"), "pipeline_source": node.get("source"),
                      "same": _same(sh.get("value"), node.get("value"))})
    block = [BEGIN,
             "      # Attributes below were added by the public-data pipeline; everything above is the hand-built file, unchanged."]
    block.append(_dump(new, 6).rstrip("\n"))
    block.append(f"# catalog_overrides: verbatim copies of the hospital-specific nodes of catalog/*.yaml (they were written for CCN {t.ccn}), so that this")
    block.append("# hospital keeps its values when another hospital is loaded or the shared files change. Same values => same simulation.")
    block.append(_dump({"catalog_overrides": overrides}).rstrip("\n"))
    block.append(END)
    out = text.rstrip("\n") + "\n" + "\n".join(block) + "\n"
    after = yaml.safe_load(out)
    assert all(after["variants"][t.id]["attributes"][k] == v for k, v in have.items()), "existing attributes changed"
    atomic_write_text(path, out)
    return dict(mode="augmented", attrs=after["variants"][t.id]["attributes"], overrides=overrides, check=check, added=sorted(new))


def build(ccn, hospital_id: str, label=None, expect=None, fetch: bool = False, write_layout: bool = True) -> dict:
    ccn = norm_ccn(ccn)
    if fetch or any(read_extract(ccn, s) is None for s in SOURCES):
        from .fetch import fetch_all
        fetch_all(ccn, force=False, skip_existing=not fetch)
    t = Twin(ccn, hospital_id, label, expect)
    path = HOSP / f"{hospital_id}.yaml"
    hand_built = path.exists() and yaml.safe_load(path.read_text()).get("generated_by") != "twin.build"
    res = write_augmented(t, path) if hand_built else write_generated(t)
    lay_summary = None
    if not hand_built and write_layout:
        counts, notes, srcs = t.layout_inputs()
        lay = layout_mod.build(hospital_id, t.label, counts, notes, srcs)
        lay_summary = lay["_summary"]
        layout_mod.write(lay, hospital_id)
    elif hand_built:
        lay_summary = f"{hospital_id}: hand-built layout catalog/hospitals/{hospital_id}.layout.json left untouched"
    md = report.render(t, res, lay_summary)
    out = REPO / "twin" / "reports" / hospital_id / "DATA.md"
    atomic_write_text(out, md)
    cov = report.coverage(res["attrs"], res["overrides"])
    atomic_write_text(out.with_name("coverage.json"), json.dumps({"hospital_id": hospital_id, "ccn": ccn, "mode": res["mode"], **cov}, indent=1) + "\n")
    print(f"[{hospital_id}] {t.fac['Facility Name']}, {t.fac.get('Address')}, {t.fac.get('City/Town')} {t.fac.get('State')}  (CCN {ccn}; {res['mode']})")
    print(f"[{hospital_id}] attributes {cov['hospital']}  overrides {cov['overrides']}  total {cov['total']}")
    print(f"[{hospital_id}] wrote catalog/hospitals/{hospital_id}.yaml" + ("" if hand_built or not write_layout else f", catalog/hospitals/{hospital_id}.layout.json") + f", twin/reports/{hospital_id}/DATA.md")
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ccn", required=True, help="CMS certification number, e.g. 330024")
    ap.add_argument("--id", required=True, help="hospital id used for file names, e.g. mount_sinai")
    ap.add_argument("--label", help="display label (default: '<CMS facility name> (model)')")
    ap.add_argument("--expect", nargs="*", help="words that must appear in the CMS facility name or city (guards against a wrong CMS number)")
    ap.add_argument("--fetch", action="store_true", help="re-run every source module first (network; heavy sources want a workstation)")
    ap.add_argument("--no-layout", action="store_true")
    a = ap.parse_args()
    build(a.ccn, a.id, a.label, a.expect, a.fetch, not a.no_layout)


if __name__ == "__main__":
    main()
