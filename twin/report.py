def coverage(attrs: dict, overrides: dict) -> dict:
    def cnt(d):
        c = Counter((v.get("source") if isinstance(v, dict) else None) or "untagged" for v in d.values())
        return {k: c.get(k, 0) for k in TAGS + (["untagged"] if c.get("untagged") else [])}
    h, o = cnt(attrs), cnt(overrides)
    return {"hospital": h, "overrides": o, "total": {k: h.get(k, 0) + o.get(k, 0) for k in TAGS},
            "n_attributes": len(attrs) + len(overrides)}


def _v(v, n=90) -> str:
    if isinstance(v, float):
        s = f"{v:,.4f}".rstrip("0").rstrip(".") if abs(v) < 1000 else f"{v:,.1f}".rstrip("0").rstrip(".")
    elif isinstance(v, bool):
        s = str(v)
    elif isinstance(v, int):
        s = f"{v:,}" if abs(v) >= 10000 else str(v)
    elif isinstance(v, (list, dict)):
        s = json.dumps(v, separators=(", ", ": "))
    else:
        s = str(v)
    return s if len(s) <= n else s[:n - 1] + "..."


def _c(s) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ")


def _table(rows, head):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(_c(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def _attr_rows(d: dict):
    rows = []
    for k, n in d.items():
        cite = n.get("citation", "")
        extra = []
        if n.get("range") is not None:
            extra.append(f"Range {_v(n['range'])}.")
        if n.get("note"):
            extra.append(n["note"])
        if n.get("validation_only"):
            extra.append("Validation target, not a simulator input.")
        if n.get("file"):
            extra.append(f"Extract: `{n['file']}`.")
        rows.append([f"`{k}`", _v(n.get("value")), n.get("unit", ""), f"**{n.get('source')}**", cite + (" - " + " ".join(extra) if extra else "")])
    return rows


def render(t: Twin, res: dict, layout_summary: str | None) -> str:
    attrs, overrides = res["attrs"], res["overrides"]
    cov = coverage(attrs, overrides)
    f = t.fac
    L = []
    w = L.append
    g = lambda k: (attrs.get(k) or {}).get("value")  # noqa: E731
    w(f"# {t.name} - data behind the digital twin (`{t.id}`)")
    w("")
    w(f"Generated by `python -m twin.build --ccn {t.ccn} --id {t.id}` on {dt.date.today().isoformat()} from the tracked extracts in `data/processed/hospitals/{t.ccn}/`. "
      "Do not edit by hand - edit `twin/derive.py` and rebuild.")
    w("")
    w(f"**Hospital (as listed by CMS):** {f['Facility Name']}, {f.get('Address')}, {f.get('City/Town')}, {f.get('State')} {f.get('ZIP Code')} - CMS certification number "
      f"**{t.ccn}** - {f.get('Hospital Type')}, {f.get('Hospital Ownership')}, emergency services: {f.get('Emergency Services')}, CMS overall rating: {f.get('Hospital overall rating')}.")
    w("")
    w("This is a model built from public data alone. It is not affiliated with or endorsed by the hospital, and nothing here is the hospital's operational data. "
      "A CMS certification number can cover more than one campus; every figure below is for the certification number as a whole.")
    w("")
    w("Source tags: **measured** = read from a public dataset for this hospital (or its labour market / HHS region) - the citation names the dataset, release, filter and field; "
      "**literature** = a published figure not specific to a dataset row; **assumed** = a stated rule or a model parameter, with the rule in the citation. "
      "No number is a guess labelled as measured.")
    w("")
    w("## Coverage")
    w("")
    rows = [["Hospital attributes (`variants." + t.id + ".attributes`)", *[cov["hospital"][k] for k in TAGS], sum(cov["hospital"][k] for k in TAGS)],
            ["Hospital-specific overrides of the shared catalog (`catalog_overrides`)", *[cov["overrides"][k] for k in TAGS], sum(cov["overrides"][k] for k in TAGS)],
            ["**Total**", *[f"**{cov['total'][k]}**" for k in TAGS], f"**{sum(cov['total'].values())}**"]]
    w(_table(rows, ["", "measured", "literature", "assumed", "all"]))
    w("")
    if res["mode"] == "augmented":
        w(f"`catalog/hospitals/{t.id}.yaml` is hand-built; the pipeline only ADDED {len(res.get('added', []))} attributes and the `catalog_overrides` block (verbatim copies of the "
          "shared-catalog nodes, which were written for this hospital). Existing values were not changed; the layout was not regenerated.")
        w("")
    w("## Key numbers")
    w("")
    keys = [("ED visits per year (CMS OP-22 denominator)", "ed_visits_per_year_cms"), ("ED visits per year (HHS weekly series, annualised)", "ed_visits_per_year_hhs"),
            ("Median ED time, discharged patients, minutes (OP-18b)", "validation_median_ed_time_min"), ("Left without being seen (OP-22)", "validation_lwbs_rate"),
            ("Beds available (cost report)", "licensed_beds"), ("ICU beds (cost report)", "icu_beds"), ("Inpatient occupancy (cost report)", "inpatient_occupancy"),
            ("Inpatient occupancy (HHS weekly)", "inpatient_occupancy_hhs"), ("Discharges per year", "inpatient_discharges_per_year"),
            ("ED direct cost per year, USD", "ed_direct_cost_per_year"), ("ED salaries per year, USD", "ed_salaries_per_year"),
            ("Clinicians affiliated (CMS)", "clinicians_affiliated_total"), ("Emergency physicians affiliated", "em_physicians"),
            ("ED nurse practitioners / physician assistants (lower bound)", "em_apps"), ("Interns and residents, FTE", "residents_fte"),
            ("Registered nurses, FTE, hospital-wide", "rn_fte"), ("Employees on payroll, FTE", "fte_employees"),
            ("ED treatment spaces", "ed_treatment_spaces"), ("Modelled inpatient pool, beds", "ward_pool_beds")]
    w(_table([[lab, _v(g(k)) if g(k) is not None else "not available", (attrs.get(k) or {}).get("source", "-"), f"`{k}`"] for lab, k in keys], ["", "Value", "Tag", "Attribute"]))
    w("")
    w("## Where public figures disagree")
    w("")
    if t.disagreements:
        w(_table([[d["what"], d["figures"], d["model_uses"]] for d in t.disagreements], ["What", "Figures", "Which one the model uses"]))
    else:
        w("None found between the sources used.")
    w("")
    for n in t.notes:
        w(f"- {n}")
    if t.notes:
        w("")
    w("## Not public - assumed")
    w("")
    w("Everything tagged `assumed`. These are rules and model parameters, not facts about the hospital; the calibration step may refit them.")
    w("")
    arows = [[f"`{k}`", _v(n.get("value")), n.get("unit", ""), n.get("citation", "")] for k, n in attrs.items() if n.get("source") == "assumed"]
    arows += [[f"`{k}`", _v(n.get("value")), n.get("unit", ""), n.get("citation", "")] for k, n in overrides.items() if n.get("source") == "assumed"]
    w(_table(arows, ["Attribute", "Value", "Unit", "Rule / reasoning"]))
    w("")
    w("## Could not be sourced")
    w("")
    if t.missing:
        w(_table([[m["what"], m["why"], m["consequence"]] for m in t.missing], ["What", "Why", "What the build did"]))
    else:
        w("Every source returned data for this hospital.")
    w("")
    w("## Still national, not hospital-specific")
    w("")
    w("These stay at the shared catalog's values for every hospital because no public facility-level source exists:")
    w("")
    w(_table([[f"`{a}`", b] for a, b in STILL_NATIONAL], ["Catalog attributes", "Why"]))
    w("")
    r = t.E.get("roster")
    w("## Clinician roster")
    w("")
    if r:
        n = r["counts"]
        w(f"One row per clinician (NPI, primary specialty, credential, graduation year - no names) is in `data/processed/hospitals/{t.ccn}/roster.json`. "
          f"{n['clinicians_affiliated_total']} clinicians are affiliated with this certification number in CMS's Facility Affiliation file; "
          f"{n['affiliated_with_other_hospitals_too']} of them are affiliated with other hospitals as well.")
        w("")
        lab = {"clinicians_affiliated_total": "All affiliated clinicians", "physicians_total": "Physicians", "apps_total": "Nurse practitioners + physician assistants (all departments)",
               "nurse_practitioners": "- nurse practitioners", "physician_assistants": "- physician assistants", "em_physicians": "Emergency medicine physicians (primary specialty)",
               "em_physicians_only_this_hospital": "- affiliated with this hospital only", "em_physicians_secondary_specialty": "Emergency medicine as a secondary specialty (not counted above)",
               "em_physicians_nppes_taxonomy_only": "Emergency-medicine NPPES taxonomy only (not counted above)",
               "em_physicians_billing_ed_visits": "Emergency physicians who billed 11+ ED visits to original Medicare in 2024",
               "em_apps": "NPs/PAs who billed 11+ ED visits under their own NPI (ED advanced practice providers, lower bound)",
               "non_em_physicians_billing_ed_visits": "Other physicians who billed 11+ ED visits", "ed_visit_services_billed_by_em_physicians": "ED visit services billed by the emergency physicians (Medicare FFS, anywhere)",
               "ed_visit_services_billed_by_em_apps": "ED visit services billed by those NPs/PAs", "hospitalists": "Hospitalists", "radiologists": "Radiologists (diagnostic + interventional)",
               "critical_care_physicians": "Critical care physicians", "anesthesiologists": "Anesthesiologists", "crnas": "Nurse anaesthetists", "internal_medicine_physicians": "Internal medicine",
               "general_surgeons": "General surgeons", "cardiologists": "Cardiologists", "neurologists": "Neurologists", "psychiatrists": "Psychiatrists", "orthopedic_surgeons": "Orthopedic surgeons"}
        w(_table([[lab[k], _v(n[k]) if n.get(k) is not None else "not available"] for k in lab if k in n], ["Group", "Clinicians"]))
        w("")
        gy = r.get("em_physician_graduation_year") or {}
        if gy.get("median"):
            w(f"Emergency physicians' medical-school graduation year: median {gy['median']:.0f}, range {gy['min']}-{gy['max']}.")
            w("")
        w("By primary specialty (CMS National Downloadable File `pri_spec`):")
        w("")
        bs = r["by_specialty"]
        top, rest = bs[:30], bs[30:]
        rows = [[x["pri_spec"].title(), x["n"]] for x in top]
        if rest:
            rows.append([f"{len(rest)} other specialties", sum(x["n"] for x in rest)])
        w(_table(rows, ["Primary specialty", "Clinicians"]))
        w("")
        w("What the roster does NOT cover:")
        w("")
        for x in r["not_covered"]:
            w(f"- {x}")
        w("")
        w("Definitions: " + " ".join(f"`{k}` = {v}." for k, v in r["definitions"].items() if k in ("em_physicians", "em_apps", "n_hospitals")))
    else:
        w("Not available: " + t.src_unavailable("roster"))
    w("")
    w("## Sources")
    w("")
    rows = []
    for s in SOURCES:
        e = t.E.get(s)
        log = (t.fetch_log.get("sources") or {}).get(s) or {}
        if not e:
            rows.append([s, "-", "-", "-", "-", "**not available**: " + (log.get("error") or "not fetched")])
            continue
        src = e["source"]
        comps = src.get("components") or ({k: v for k, v in src.items() if isinstance(v, dict) and v.get("dataset")} if "dataset" not in src else None)
        if comps:
            for k, v in comps.items():
                rows.append([f"{s} / {k}", v.get("dataset", ""), v.get("release") or "", (v.get("fetched_utc") or "")[:19], (v.get("sha256") or "-")[:12],
                             (v.get("filter") or "") + (f" UNAVAILABLE: {v['unavailable']}" if v.get("unavailable") else "")])
            for k, v in (src.get("unavailable") or {}).items():
                rows.append([f"{s} / {k}", "-", "-", "-", "-", f"**not available**: {v}"])
        else:
            rows.append([s, src.get("dataset", ""), src.get("release") or "", (src.get("fetched_utc") or "")[:60], (src.get("sha256") or "-")[:12], src.get("filter") or ""])
    w(_table(rows, ["Extract", "Dataset", "Release / vintage", "Fetched (UTC)", "sha256 (first 12)", "Filter"]))
    w("")
    w(f"Full URLs, hashes and byte counts are in each extract's `source` block (`data/processed/hospitals/{t.ccn}/<extract>.json`); raw downloads are under `data/raw/` (not tracked).")
    w("")
    if layout_summary:
        w("## Layout")
        w("")
        w("Every room position is `inferred` - no interior plan was used - unless the file is hand-built. Counts come from the attributes above." if res["mode"] != "augmented"
          else "Hand-built layout (see research/hospital-layout-rwjuh.md); not regenerated by this pipeline.")
        w("")
        w("```\n" + layout_summary + "\n```")
        w("")
    if res.get("check"):
        w("## Pipeline check against the hand-built values")
        w("")
        same = sum(1 for c in res["check"] if c["same"])
        w(f"The shared catalog was hand-wired for this hospital. Re-deriving the same {len(res['check'])} values with the generic pipeline reproduces {same} of them (within 0.5 percent). "
          "Where they differ the simulator keeps the catalog value (that is what `catalog_overrides` holds); the difference is explained by the pipeline's default choice.")
        w("")
        why = {"staff.shared.": "the rule scales RWJUH's own roster by arrivals, so any difference is rounding",
               "staff.": "the hand-built catalog uses New Jersey statewide wages, the pipeline uses the metropolitan area (New York-Newark-Jersey City)",
               "patient.shared.arrival_month_profile": "the catalog keeps the assumed national profile; the pipeline would use this hospital's HHS weekly series",
               "space.": "the hand-built ED split uses the hand-built space counts; pipeline value recomputed from the same cost report",
               "event.": "same series; any difference is the fetch date"}
        rows = []
        for c in res["check"]:
            reason = "" if c["same"] else next((v for k, v in why.items() if c["path"].startswith(k)), "")
            rows.append([f"`{c['path']}`", _v(c["catalog"], 60), c["catalog_source"], _v(c["pipeline"], 60), c["pipeline_source"], "yes" if c["same"] else "NO", reason])
        w(_table(rows, ["Path", "Catalog (used)", "Tag", "Pipeline", "Tag", "Same", "If not, why"]))
        w("")
    w("## Every hospital attribute")
    w("")
    w(_table(_attr_rows(attrs), ["Attribute", "Value", "Unit", "Tag", "Citation, range and notes"]))
    w("")
    w("## Hospital-specific values of shared-catalog attributes (`catalog_overrides`)")
    w("")
    w("Applied on top of `catalog/*.yaml` when this hospital is loaded (`sim/config.py`); path = `<file>.<variant or shared>.<key>`.")
    w("")
    w(_table(_attr_rows(overrides), ["Path", "Value", "Unit", "Tag", "Citation, range and notes"]))
    w("")
    return "\n".join(L)
